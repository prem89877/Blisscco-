-- authorised members -----------------------------------------------------------------------------------------------
create or replace function public.megastore_add_member(p_email text) returns void
language plpgsql security definer set search_path = '' as $$
declare m public.mega_stores; v_uid uuid;
begin
  if not public.is_owner() then raise exception 'owner_only' using errcode = '42501'; end if;
  select * into m from public.mega_stores where owner_id = auth.uid();                    -- only the PRIMARY owner manages members
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if m.status <> 'approved' then raise exception 'store_not_approved'; end if;
  select u.id into v_uid from auth.users u where lower(u.email::text) = lower(trim(coalesce(p_email, '')));
  if v_uid is null or v_uid = auth.uid()
     or not exists (select 1 from public.profiles p where p.id = v_uid and p.role = 'owner' and not p.is_suspended) then
    raise exception 'user_not_eligible';                                                  -- same answer for every failure (no e-mail probing)
  end if;
  insert into public.mega_store_members (mega_store_id, user_id, member_role, added_by)
  values (m.id, v_uid, 'manager', auth.uid())
  on conflict (mega_store_id, user_id) do update set status = 'active', revoked_at = null, added_by = auth.uid()
   where public.mega_store_members.status = 'revoked';
end $$;

create or replace function public.megastore_revoke_member(p_user_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare m public.mega_stores;
begin
  if not public.is_owner() then raise exception 'owner_only' using errcode = '42501'; end if;
  select * into m from public.mega_stores where owner_id = auth.uid();
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  update public.mega_store_members set status = 'revoked', revoked_at = now()
   where mega_store_id = m.id and user_id = p_user_id and status = 'active';             -- the primary owner is protected by the trigger
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
end $$;

-- budget -----------------------------------------------------------------------------------------------------------
create or replace function public.megastore_set_campaign_budget(p_campaign_id uuid, p_budget numeric) returns void
language plpgsql security definer set search_path = '' as $$
declare c public.mega_campaigns; v_status text;
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into c from public.mega_campaigns where id = p_campaign_id for update;
  if not found or not (public.owns_mega_store(c.mega_store_id) or public.is_admin()) then raise exception 'not_found' using errcode = 'P0002'; end if;
  select status into v_status from public.mega_stores where id = c.mega_store_id;
  if v_status <> 'approved' and not public.is_admin() then raise exception 'store_not_approved'; end if;
  if c.status = 'ended' then raise exception 'campaign_locked'; end if;
  if p_budget is not null and (p_budget <= 0 or p_budget > 1000000000) then raise exception 'invalid_budget'; end if;
  update public.mega_campaigns set budget_inr = p_budget where id = c.id;                  -- trigger refuses a budget below what was spent
end $$;

create or replace function public.get_mega_campaign_budget(p_campaign_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare c public.mega_campaigns; v_spent numeric; v_n int;
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into c from public.mega_campaigns where id = p_campaign_id;
  if not found or not (public.owns_mega_store(c.mega_store_id) or public.is_admin()) then raise exception 'not_found' using errcode = 'P0002'; end if;
  select coalesce(sum(discount_inr), 0), count(*)::int into v_spent, v_n from public.mega_reward_redemptions where campaign_id = c.id;
  return jsonb_build_object('campaign_id', c.id, 'budget_inr', c.budget_inr, 'spent_inr', v_spent, 'redemptions', v_n,
    'remaining_inr', case when c.budget_inr is null then null else greatest(c.budget_inr - v_spent, 0) end);
end $$;

-- terms ------------------------------------------------------------------------------------------------------------
create or replace function public._mega_insert_terms(p_campaign_id uuid, p_scope text, p_title text, p_body text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare v_ver int; v_id uuid;
begin
  if p_scope not in ('customer', 'partner') then raise exception 'invalid_scope'; end if;
  perform pg_advisory_xact_lock(hashtext('mega_terms:' || coalesce(p_campaign_id::text, 'default') || ':' || p_scope));
  select coalesce(max(version), 0) + 1 into v_ver from public.mega_terms
   where scope = p_scope and coalesce(campaign_id, '00000000-0000-0000-0000-000000000000'::uuid) = coalesce(p_campaign_id, '00000000-0000-0000-0000-000000000000'::uuid);
  insert into public.mega_terms (campaign_id, scope, version, title, body_md, created_by)
  values (p_campaign_id, p_scope, v_ver, trim(p_title), p_body, auth.uid()) returning id into v_id;
  return v_id;
end $$;

create or replace function public.admin_publish_mega_terms(p_scope text, p_title text, p_body text, p_campaign_id uuid default null) returns uuid
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'admin only' using errcode = '42501'; end if;
  if p_campaign_id is not null and not exists (select 1 from public.mega_campaigns where id = p_campaign_id) then raise exception 'not_found' using errcode = 'P0002'; end if;
  return public._mega_insert_terms(p_campaign_id, p_scope, p_title, p_body);
end $$;

-- the Mega Store owner can attach terms to their own campaign while it is still a draft
create or replace function public.megastore_publish_campaign_terms(p_scope text, p_title text, p_body text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare m public.mega_stores; c public.mega_campaigns;
begin
  if not public.is_owner() then raise exception 'owner_only' using errcode = '42501'; end if;
  select * into m from public.mega_stores where owner_id = auth.uid();
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if m.status <> 'approved' then raise exception 'store_not_approved'; end if;
  select * into c from public.mega_campaigns where mega_store_id = m.id and status in ('draft', 'active', 'paused') for update;
  if not found then raise exception 'no_campaign'; end if;
  if c.status <> 'draft' then raise exception 'campaign_locked'; end if;
  return public._mega_insert_terms(c.id, p_scope, p_title, p_body);
end $$;

create or replace function public.get_mega_terms(p_campaign_id uuid, p_scope text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare t public.mega_terms; v_id uuid; v_acc boolean := false;
begin
  if p_scope not in ('customer', 'partner') then raise exception 'invalid_scope'; end if;
  if not public.mega_terms_visible(p_campaign_id) then raise exception 'not_found' using errcode = 'P0002'; end if;
  v_id := public.mega_current_terms(p_campaign_id, p_scope);
  if v_id is null then return jsonb_build_object('terms', null, 'accepted', false); end if;
  select * into t from public.mega_terms where id = v_id;
  if auth.uid() is not null and p_campaign_id is not null then
    select exists (select 1 from public.mega_terms_acceptances a where a.terms_id = v_id and a.user_id = auth.uid() and a.campaign_id = p_campaign_id) into v_acc;
  end if;
  return jsonb_build_object('terms', jsonb_build_object('id', t.id, 'version', t.version, 'title', t.title, 'body_md', t.body_md), 'accepted', v_acc);
end $$;

-- records that the SIGNED-IN user accepted the CURRENT terms (the user id and the version come from the server, not the browser)
create or replace function public.accept_mega_terms(p_campaign_id uuid, p_scope text, p_business_id uuid default null) returns void
language plpgsql security definer set search_path = '' as $$
declare c public.mega_campaigns; pr public.profiles; v_terms uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into pr from public.profiles where id = auth.uid();
  if not found or pr.is_suspended then raise exception 'not_available' using errcode = '42501'; end if;
  select * into c from public.mega_campaigns where id = p_campaign_id;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if p_scope = 'customer' then
    if pr.role <> 'customer' then raise exception 'customer_only'; end if;
    if c.status <> 'active' or c.ends_at <= now() then raise exception 'not_active'; end if;
  elsif p_scope = 'partner' then
    if p_business_id is null or not public.owns_business(p_business_id) then raise exception 'not_authorized' using errcode = '42501'; end if;
    if not exists (select 1 from public.mega_campaign_shops s where s.campaign_id = c.id and s.business_id = p_business_id) then raise exception 'not_partner_shop'; end if;
  else
    raise exception 'invalid_scope';
  end if;
  v_terms := public.mega_current_terms(c.id, p_scope);
  if v_terms is null then raise exception 'no_terms'; end if;
  insert into public.mega_terms_acceptances (terms_id, user_id, campaign_id, scope, business_id)
  values (v_terms, auth.uid(), c.id, p_scope, case when p_scope = 'partner' then p_business_id end)
  on conflict do nothing;
end $$;

-- partner shops ----------------------------------------------------------------------------------------------------
create or replace function public.partner_respond_mega_campaign(p_campaign_id uuid, p_business_id uuid, p_accept boolean) returns void
language plpgsql security definer set search_path = '' as $$
declare p public.mega_partner_participation; c public.mega_campaigns; v_terms uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if not public.owns_business(p_business_id) then raise exception 'not_authorized' using errcode = '42501'; end if;
  select * into c from public.mega_campaigns where id = p_campaign_id;
  if not found or c.status = 'ended' then raise exception 'not_active'; end if;
  select * into p from public.mega_partner_participation where campaign_id = p_campaign_id and business_id = p_business_id for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if p_accept is true then
    if p.status <> 'invited' then raise exception 'invalid_transition'; end if;
    v_terms := public.mega_current_terms(c.id, 'partner');
    if v_terms is not null and not exists (select 1 from public.mega_terms_acceptances a
         where a.terms_id = v_terms and a.user_id = auth.uid() and a.campaign_id = c.id and a.business_id = p_business_id) then
      raise exception 'terms_not_accepted';
    end if;
    update public.mega_partner_participation set status = 'accepted', responded_at = now(), responded_by = auth.uid(), terms_id = v_terms
     where campaign_id = p.campaign_id and business_id = p.business_id;
  else
    if p.status not in ('invited', 'accepted') then raise exception 'invalid_transition'; end if;
    update public.mega_partner_participation
       set status = case when p.status = 'accepted' then 'withdrawn' else 'declined' end, responded_at = now(), responded_by = auth.uid()
     where campaign_id = p.campaign_id and business_id = p.business_id;
    delete from public.mega_campaign_shops where campaign_id = p.campaign_id and business_id = p.business_id;   -- stops new rewards at this shop
  end if;
end $$;

-- a partner shop sees ONLY the verification facts it needs (no reward code, amount or customer contact)
create or replace function public.partner_list_mega_services(p_business_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_out jsonb;
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if not public.owns_business(p_business_id) then raise exception 'not_authorized' using errcode = '42501'; end if;
  select coalesce(jsonb_agg(x.j order by x.at desc), '[]'::jsonb) into v_out
    from (select v.verified_at as at,
                 jsonb_build_object('booking_id', v.booking_id, 'status', v.status, 'service', v.service_label, 'price_inr', v.service_price_inr,
                   'completed_at', v.service_completed_at, 'verified_at', v.verified_at, 'campaign_title', c.title, 'store_name', ms.name,
                   'customer_first_name', coalesce(split_part(p.full_name, ' ', 1), '')) as j
            from public.mega_service_verifications v
            join public.mega_campaigns c on c.id = v.campaign_id
            join public.mega_stores ms on ms.id = v.mega_store_id
            join public.profiles p on p.id = v.customer_id
           where v.business_id = p_business_id
           order by v.verified_at desc limit 100) x;
  return v_out;
end $$;

-- admin ------------------------------------------------------------------------------------------------------------
create or replace function public.admin_mega_set_service_status(p_booking_id uuid, p_status text, p_note text default null) returns void
language plpgsql security definer set search_path = '' as $$
declare v public.mega_service_verifications;
begin
  if not public.is_admin() then raise exception 'admin only' using errcode = '42501'; end if;
  if p_status not in ('verified', 'revoked', 'rejected') then raise exception 'invalid_status'; end if;
  select * into v from public.mega_service_verifications where booking_id = p_booking_id for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  update public.mega_service_verifications
     set status = p_status, method = 'admin', verified_by = auth.uid(), note = left(nullif(trim(coalesce(p_note, '')), ''), 300)
   where id = v.id;
  if p_status <> 'verified' then                                     -- an unverified service cannot back a reward (redeemed ones stay as history)
    update public.mega_rewards set status = 'revoked', review_note = left(nullif(trim(coalesce(p_note, '')), ''), 300),
           reviewed_by = auth.uid(), reviewed_at = now()
     where booking_id = p_booking_id and status in ('active', 'on_hold');
  end if;
end $$;

create or replace function public.admin_mega_review_flag(p_flag_id uuid, p_decision text, p_note text default null) returns void
language plpgsql security definer set search_path = '' as $$
declare f public.mega_fraud_flags;
begin
  if not public.is_admin() then raise exception 'admin only' using errcode = '42501'; end if;
  if p_decision not in ('cleared', 'confirmed') then raise exception 'invalid_decision'; end if;
  select * into f from public.mega_fraud_flags where id = p_flag_id for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if f.status <> 'open' then raise exception 'invalid_transition'; end if;
  update public.mega_fraud_flags set status = p_decision, reviewed_by = auth.uid(), reviewed_at = now(),
         review_note = left(nullif(trim(coalesce(p_note, '')), ''), 300) where id = f.id;
  if p_decision = 'confirmed' and f.reward_id is not null then      -- confirmed fraud cancels the reward if it is not redeemed yet
    update public.mega_rewards set status = 'revoked', review_note = left(nullif(trim(coalesce(p_note, '')), ''), 300),
           reviewed_by = auth.uid(), reviewed_at = now()
     where id = f.reward_id and status in ('active', 'on_hold');
  end if;
end $$;

create or replace function public.admin_mega_raise_flag(p_reward_id uuid, p_flag_type text, p_note text default null) returns uuid
language plpgsql security definer set search_path = '' as $$
declare r public.mega_rewards; v_id uuid; v_type text := lower(trim(coalesce(p_flag_type, '')));
begin
  if not public.is_admin() then raise exception 'admin only' using errcode = '42501'; end if;
  if v_type !~ '^[a-z0-9_]{3,40}$' then raise exception 'invalid_flag_type'; end if;
  select * into r from public.mega_rewards where id = p_reward_id;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  insert into public.mega_fraud_flags (campaign_id, mega_store_id, reward_id, customer_id, business_id, flag_type, severity, source, details)
  values (r.campaign_id, r.mega_store_id, r.id, r.customer_id, r.business_id, v_type, 'high', 'admin',
          jsonb_build_object('note', left(nullif(trim(coalesce(p_note, '')), ''), 300)))
  on conflict do nothing returning id into v_id;
  if v_id is null then raise exception 'already_flagged'; end if;
  return v_id;
end $$;

