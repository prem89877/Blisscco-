on conflict (reward_id) do nothing;

insert into public.mega_fraud_flags (campaign_id, mega_store_id, reward_id, customer_id, business_id, flag_type, status, details)
select r.campaign_id, r.mega_store_id, r.id, r.customer_id, r.business_id,
       lower(regexp_replace(f.v, '[^a-zA-Z0-9_]', '_', 'g')),
       case r.status when 'on_hold' then 'open' when 'rejected' then 'confirmed' when 'revoked' then 'confirmed' else 'cleared' end,
       jsonb_build_object('backfilled', true)
  from public.mega_rewards r
  cross join lateral jsonb_array_elements_text(r.risk_flags) as f(v)
 where jsonb_typeof(r.risk_flags) = 'array' and char_length(f.v) between 3 and 40
on conflict do nothing;

