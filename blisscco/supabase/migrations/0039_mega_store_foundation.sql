-- members: the primary owner can never be demoted / revoked, and a member row never moves to another store or user
create or replace function public.mega_members_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.mega_store_id <> old.mega_store_id or new.user_id <> old.user_id then raise exception 'record_immutable' using errcode = '42501'; end if;
  if exists (select 1 from public.mega_stores s where s.id = new.mega_store_id and s.owner_id = new.user_id)
     and (new.status <> 'active' or new.member_role <> 'owner') then
    raise exception 'primary_owner_locked';
  end if;
  return new;
end $$;

create or replace function public.mega_store_add_owner_member() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.mega_store_members (mega_store_id, user_id, member_role, added_by)
  values (new.id, new.owner_id, 'owner', new.owner_id) on conflict do nothing;
  return new;
end $$;

-- campaigns: reward terms are frozen once the campaign leaves draft; 'ended' is final; budget can never drop below what was spent
create or replace function public.mega_campaign_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_spent numeric;
begin
  if new.mega_store_id <> old.mega_store_id then raise exception 'campaign_locked'; end if;
  if old.status = 'ended' and new.status <> 'ended' then raise exception 'invalid_transition'; end if;
  if old.status <> 'draft' and (new.reward_type <> old.reward_type or new.reward_value <> old.reward_value
       or new.max_discount_inr is distinct from old.max_discount_inr or new.min_purchase_inr <> old.min_purchase_inr
       or new.min_service_price_inr <> old.min_service_price_inr or new.max_rewards_per_customer <> old.max_rewards_per_customer
       or new.one_reward_per_shop <> old.one_reward_per_shop or new.starts_at <> old.starts_at) then
    raise exception 'campaign_locked';
  end if;
  if new.budget_inr is not null and new.budget_inr is distinct from old.budget_inr then
    select coalesce(sum(discount_inr), 0) into v_spent from public.mega_reward_redemptions where campaign_id = new.id;
    if new.budget_inr < v_spent then raise exception 'budget_below_spent'; end if;
  end if;
  return new;
end $$;

-- partner selection -> participation record. A shop that declined cannot be forced back in.
create or replace function public.mega_shop_link_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare p public.mega_partner_participation;
begin
  select * into p from public.mega_partner_participation where campaign_id = new.campaign_id and business_id = new.business_id for update;
  if not found then
    insert into public.mega_partner_participation (campaign_id, business_id) values (new.campaign_id, new.business_id);
  elsif p.status = 'declined' then
    raise exception 'partner_declined';
  elsif p.status in ('withdrawn', 'removed') then
    update public.mega_partner_participation set status = 'invited', invited_at = now(), responded_at = null, responded_by = null, terms_id = null
     where campaign_id = new.campaign_id and business_id = new.business_id;
  end if;
  return new;
end $$;

create or replace function public.mega_shop_unlink() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.mega_partner_participation set status = 'removed', responded_at = now()
   where campaign_id = old.campaign_id and business_id = old.business_id and status in ('invited', 'accepted');
  return null;
end $$;

-- enrolment: authenticated real customer, active campaign, accepted terms (when terms exist). Duplicates are left to the unique key.
create or replace function public.mega_enrollment_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare c public.mega_campaigns; ms public.mega_stores; pr public.profiles; v_terms uuid;
begin
  if exists (select 1 from public.mega_enrollments where campaign_id = new.campaign_id and customer_id = new.customer_id) then
    return new;                                         -- already joined: ON CONFLICT DO NOTHING (or the unique key) handles it
  end if;
  select * into c from public.mega_campaigns where id = new.campaign_id;
  if not found or c.status <> 'active' or c.ends_at <= now() then raise exception 'not_active'; end if;
  select * into ms from public.mega_stores where id = c.mega_store_id;
  if ms.status <> 'approved' then raise exception 'store_not_approved'; end if;
  select * into pr from public.profiles where id = new.customer_id;
  if not found or pr.is_suspended or pr.role <> 'customer' then raise exception 'customer_only'; end if;
  if ms.owner_id = new.customer_id then raise exception 'own_store'; end if;
  v_terms := public.mega_current_terms(c.id, 'customer');
  if v_terms is not null then
    if not exists (select 1 from public.mega_terms_acceptances a
                    where a.terms_id = v_terms and a.user_id = new.customer_id and a.campaign_id = c.id and a.business_id is null) then
      raise exception 'terms_not_accepted';
    end if;
    new.terms_id := v_terms;
  end if;
  return new;
end $$;

-- rewards: THE central guard. Runs for every role (including the table owner), so the rules cannot be skipped by a bad function.
create or replace function public.mega_reward_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  c public.mega_campaigns; ms public.mega_stores; bk public.bookings; biz public.businesses; en public.mega_enrollments;
  v_ver public.mega_service_verifications; v_seq smallint; v_spent numeric; v_exp numeric;
begin
  if tg_op = 'INSERT' then
    if new.status not in ('active', 'on_hold') or new.redeemed_at is not null or new.redeemed_bill_inr is not null
       or new.discount_given_inr is not null then
      raise exception 'invalid_initial_status';
    end if;
    select * into c from public.mega_campaigns where id = new.campaign_id;
    if not found or c.mega_store_id <> new.mega_store_id then raise exception 'campaign_mismatch'; end if;
    select * into ms from public.mega_stores where id = c.mega_store_id;
    -- the customer must have joined; this row lock serialises two rewards for the same customer (so the cap cannot be beaten)
    select * into en from public.mega_enrollments where campaign_id = c.id and customer_id = new.customer_id for update;
    if not found then raise exception 'not_enrolled'; end if;
    -- the verified partner-shop service
    select * into bk from public.bookings where id = new.booking_id;
    if not found or bk.status <> 'completed' or bk.source <> 'customer' or bk.customer_id is distinct from new.customer_id
       or bk.business_id <> new.business_id then
      raise exception 'service_not_verified';
    end if;
    select * into biz from public.businesses where id = bk.business_id;
    if not exists (select 1 from public.mega_campaign_shops s where s.campaign_id = c.id and s.business_id = bk.business_id) then
      raise exception 'not_partner_shop';
    end if;
    if ms.owner_id = new.customer_id or ms.owner_id = biz.owner_id or biz.owner_id = new.customer_id then raise exception 'self_dealing'; end if;
    -- cap: at most max_rewards_per_customer (never more than 5)
    if (select count(*) from public.mega_rewards x where x.campaign_id = c.id and x.customer_id = new.customer_id
          and x.status in ('active', 'on_hold', 'redeemed')) >= least(c.max_rewards_per_customer, 5) then
      raise exception 'reward_limit_reached';
    end if;
    select min(g) into v_seq from generate_series(1, least(c.max_rewards_per_customer, 5)) g
     where not exists (select 1 from public.mega_rewards x where x.campaign_id = c.id and x.customer_id = new.customer_id
                         and x.reward_seq = g and x.status in ('active', 'on_hold', 'redeemed'));
    if v_seq is null then raise exception 'reward_limit_reached'; end if;
    if c.one_reward_per_shop and exists (select 1 from public.mega_rewards x where x.campaign_id = c.id and x.customer_id = new.customer_id
          and x.business_id = new.business_id and x.status in ('active', 'on_hold', 'redeemed')) then
      raise exception 'duplicate_shop';
    end if;
    if c.budget_inr is not null then
      select coalesce(sum(discount_inr), 0) into v_spent from public.mega_reward_redemptions where campaign_id = c.id;
      if v_spent >= c.budget_inr then raise exception 'budget_exhausted'; end if;
    end if;
    -- link / create the verification record
    insert into public.mega_service_verifications (booking_id, campaign_id, mega_store_id, customer_id, business_id, service_label,
                                                   service_price_inr, service_completed_at)
    values (bk.id, c.id, ms.id, bk.customer_id, bk.business_id, bk.service_label, bk.price_inr, bk.completed_at)
    on conflict (booking_id) do nothing;
    select * into v_ver from public.mega_service_verifications where booking_id = bk.id;
    if v_ver.status <> 'verified' or v_ver.campaign_id <> c.id or v_ver.customer_id <> new.customer_id then
      raise exception 'service_not_verified';
    end if;
    -- never trust the caller: terms, identifier, sequence and clock come from the server
    new.service_verification_id := v_ver.id;
    new.reward_seq := v_seq;
    new.reward_type := c.reward_type;
    new.reward_value := c.reward_value;
    new.max_discount_inr := c.max_discount_inr;
    new.min_purchase_inr := c.min_purchase_inr;
    new.business_name := biz.name;
    new.code := public.mega_new_reward_code();
    if new.risk_flags is null or jsonb_typeof(new.risk_flags) <> 'array' then new.risk_flags := '[]'::jsonb; end if;
    if new.status = 'active' then
      new.issued_at := now();
      new.expires_at := ((now() at time zone 'UTC') + interval '1 month') at time zone 'UTC';
    else
      new.issued_at := null; new.expires_at := null;
    end if;
    return new;
  end if;

  -- UPDATE
  if new.id <> old.id or new.campaign_id <> old.campaign_id or new.mega_store_id <> old.mega_store_id
     or new.customer_id <> old.customer_id or new.booking_id <> old.booking_id or new.business_id <> old.business_id
     or new.code <> old.code or new.business_name <> old.business_name or new.reward_type <> old.reward_type
     or new.reward_value <> old.reward_value or new.max_discount_inr is distinct from old.max_discount_inr
     or new.min_purchase_inr <> old.min_purchase_inr or new.reward_seq is distinct from old.reward_seq
     or (new.service_verification_id is distinct from old.service_verification_id and new.service_verification_id is not null)
     or new.created_at <> old.created_at or new.funded_by <> old.funded_by then
    raise exception 'reward_immutable';
  end if;

  if new.status is distinct from old.status then
    if not ((old.status = 'on_hold' and new.status in ('active', 'rejected', 'revoked'))
         or (old.status = 'active' and new.status in ('redeemed', 'revoked'))) then
      raise exception 'invalid_transition';
    end if;
    if new.status = 'active' then                                   -- released from hold: the one-month clock starts now
      new.issued_at := now();
      new.expires_at := ((now() at time zone 'UTC') + interval '1 month') at time zone 'UTC';
    elsif new.status = 'redeemed' then
      if old.expires_at is null or old.expires_at <= now() then raise exception 'expired'; end if;
      if new.redeemed_bill_inr is null or new.redeemed_bill_inr <= 0 or new.discount_given_inr is null or new.discount_given_inr < 0 then
        raise exception 'invalid_bill';
      end if;
      if new.redeemed_bill_inr < old.min_purchase_inr then raise exception 'below_min_purchase'; end if;
      v_exp := case when old.reward_type = 'percent' then round(new.redeemed_bill_inr * old.reward_value / 100, 2) else old.reward_value end;
      if old.reward_type = 'percent' and old.max_discount_inr is not null then v_exp := least(v_exp, old.max_discount_inr); end if;
      v_exp := least(v_exp, new.redeemed_bill_inr);
      if abs(new.discount_given_inr - v_exp) > 0.01 then raise exception 'discount_mismatch'; end if;     -- 1 paisa tolerance for rounding of the bill
      new.redeemed_at := now();
    end if;
  else
    -- final rows never change (only 'reviewed_by' may become null when that reviewer's account is deleted)
    if old.status in ('redeemed', 'revoked', 'rejected') and (to_jsonb(new) - 'reviewed_by') is distinct from (to_jsonb(old) - 'reviewed_by') then
      raise exception 'reward_final';
    end if;
    if new.issued_at is distinct from old.issued_at or new.expires_at is distinct from old.expires_at then
      raise exception 'reward_immutable';
    end if;
  end if;
  return new;
end $$;

-- rewards: flags, redemption record, flag decisions, audit
create or replace function public.mega_reward_after() returns trigger
language plpgsql security definer set search_path = '' as $$
declare f text; v_type text;
begin
  if tg_op = 'INSERT' then
    for f in select jsonb_array_elements_text(new.risk_flags) loop
      v_type := lower(regexp_replace(f, '[^a-zA-Z0-9_]', '_', 'g'));
      if char_length(v_type) between 3 and 40 then
        insert into public.mega_fraud_flags (campaign_id, mega_store_id, reward_id, customer_id, business_id, flag_type, source, details)
        values (new.campaign_id, new.mega_store_id, new.id, new.customer_id, new.business_id, v_type, 'system',
                jsonb_build_object('booking_id', new.booking_id))
        on conflict do nothing;
      end if;
    end loop;
    perform public.mega_audit('reward.issue', new.mega_store_id, new.campaign_id, 'mega_reward', new.id,
      jsonb_build_object('status', new.status, 'booking_id', new.booking_id, 'seq', new.reward_seq, 'flags', new.risk_flags));
    return null;
  end if;

  if new.status is distinct from old.status then
    if new.status = 'redeemed' then
      insert into public.mega_reward_redemptions (reward_id, campaign_id, mega_store_id, customer_id, redeemed_by, bill_inr, discount_inr, redeemed_at)
      values (new.id, new.campaign_id, new.mega_store_id, new.customer_id, auth.uid(), new.redeemed_bill_inr, new.discount_given_inr, new.redeemed_at);
    end if;
    if old.status = 'on_hold' and new.status = 'active' then
      update public.mega_fraud_flags set status = 'cleared', reviewed_by = auth.uid(), reviewed_at = now()
       where reward_id = new.id and status = 'open';
    elsif new.status in ('rejected', 'revoked') then
      update public.mega_fraud_flags set status = 'confirmed', reviewed_by = auth.uid(), reviewed_at = now()
       where reward_id = new.id and status = 'open';
    end if;
    perform public.mega_audit('reward.' || new.status, new.mega_store_id, new.campaign_id, 'mega_reward', new.id,
      jsonb_build_object('from', old.status, 'to', new.status));
  end if;
  return null;
end $$;

-- redemption: the campaign budget is enforced here (row lock on the campaign, so two redemptions cannot both squeeze under it)
create or replace function public.mega_redemption_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare c public.mega_campaigns; v_spent numeric;
begin
  select * into c from public.mega_campaigns where id = new.campaign_id for update;
  if not found then raise exception 'campaign_mismatch'; end if;
  if c.budget_inr is not null then
    select coalesce(sum(discount_inr), 0) into v_spent from public.mega_reward_redemptions where campaign_id = c.id;
    if v_spent + new.discount_inr > c.budget_inr then raise exception 'budget_exhausted'; end if;
  end if;
  return new;
end $$;

-- generic audit trigger for the other tables
create or replace function public.mega_audit_trigger() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_new jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  v_old jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_row jsonb;
  v_store uuid; v_camp uuid; v_ent uuid; v_action text; v_det jsonb := '{}'::jsonb;
begin
  v_row := coalesce(v_new, v_old);
  case tg_table_name
    when 'mega_stores' then
      v_store := (v_row->>'id')::uuid; v_ent := v_store;
      if tg_op = 'INSERT' then v_action := 'store.create';
      elsif v_new->>'status' is distinct from v_old->>'status' then
        v_action := 'store.' || (v_new->>'status'); v_det := jsonb_build_object('from', v_old->>'status', 'to', v_new->>'status');
      else return null; end if;
    when 'mega_campaigns' then
      v_store := (v_row->>'mega_store_id')::uuid; v_camp := (v_row->>'id')::uuid; v_ent := v_camp;
      if tg_op = 'INSERT' then
        v_action := 'campaign.create'; v_det := jsonb_build_object('status', v_new->>'status', 'budget_inr', v_new->>'budget_inr');
      else
        if v_new->>'status' is distinct from v_old->>'status' then
          v_action := 'campaign.' || (v_new->>'status'); v_det := jsonb_build_object('from', v_old->>'status', 'to', v_new->>'status');
        elsif v_new->>'budget_inr' is distinct from v_old->>'budget_inr' then
          v_action := 'campaign.budget'; v_det := jsonb_build_object('from', v_old->>'budget_inr', 'to', v_new->>'budget_inr');
        elsif v_new->>'ends_at' is distinct from v_old->>'ends_at' or (v_new->'config') is distinct from (v_old->'config') then
          v_action := 'campaign.update'; v_det := jsonb_build_object('ends_at', v_new->>'ends_at');
        else return null; end if;
      end if;
    when 'mega_campaign_shops' then
      v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'business_id')::uuid;
      v_action := case tg_op when 'INSERT' then 'shop.add' else 'shop.remove' end;
    when 'mega_enrollments' then
      v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid; v_action := 'enrollment.create';
      v_det := jsonb_build_object('customer_id', v_row->>'customer_id');
    when 'mega_partner_participation' then
      v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'business_id')::uuid;
      if tg_op = 'INSERT' then v_action := 'partner.invited';
      elsif v_new->>'status' is distinct from v_old->>'status' then
        v_action := 'partner.' || (v_new->>'status'); v_det := jsonb_build_object('from', v_old->>'status', 'to', v_new->>'status');
      else return null; end if;
    when 'mega_service_verifications' then
      v_store := (v_row->>'mega_store_id')::uuid; v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid;
      if tg_op = 'INSERT' then v_action := 'service.verified'; v_det := jsonb_build_object('booking_id', v_row->>'booking_id', 'business_id', v_row->>'business_id');
      elsif v_new->>'status' is distinct from v_old->>'status' then
        v_action := 'service.' || (v_new->>'status'); v_det := jsonb_build_object('from', v_old->>'status', 'to', v_new->>'status');
      else return null; end if;
    when 'mega_fraud_flags' then
      v_store := (v_row->>'mega_store_id')::uuid; v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid;
      if tg_op = 'INSERT' then v_action := 'flag.raise'; v_det := jsonb_build_object('type', v_row->>'flag_type', 'source', v_row->>'source');
      elsif v_new->>'status' is distinct from v_old->>'status' then
        v_action := 'flag.' || (v_new->>'status'); v_det := jsonb_build_object('type', v_row->>'flag_type', 'from', v_old->>'status');
      else return null; end if;
    when 'mega_store_members' then
      v_store := (v_row->>'mega_store_id')::uuid; v_ent := (v_row->>'user_id')::uuid;
      if tg_op = 'INSERT' then v_action := 'member.add'; v_det := jsonb_build_object('role', v_row->>'member_role');
      elsif v_new->>'status' is distinct from v_old->>'status' then v_action := 'member.' || (v_new->>'status');
      else return null; end if;
    when 'mega_terms' then
      v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid; v_action := 'terms.publish';
      v_det := jsonb_build_object('scope', v_row->>'scope', 'version', v_row->>'version');
    when 'mega_terms_acceptances' then
      v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid; v_action := 'terms.accept';
      v_det := jsonb_build_object('scope', v_row->>'scope', 'terms_id', v_row->>'terms_id', 'business_id', v_row->>'business_id');
    when 'mega_reward_redemptions' then
      v_store := (v_row->>'mega_store_id')::uuid; v_camp := (v_row->>'campaign_id')::uuid; v_ent := (v_row->>'id')::uuid;
      v_action := 'redemption.record'; v_det := jsonb_build_object('reward_id', v_row->>'reward_id', 'bill_inr', v_row->>'bill_inr', 'discount_inr', v_row->>'discount_inr');
    else
      return null;
  end case;
  if v_store is null and v_camp is not null then
    select c.mega_store_id into v_store from public.mega_campaigns c where c.id = v_camp;
  end if;
  perform public.mega_audit(v_action, v_store, v_camp, regexp_replace(tg_table_name, '^mega_', ''), v_ent, v_det);
  return null;
end $$;

