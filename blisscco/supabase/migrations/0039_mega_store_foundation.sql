-- 0039: Mega Store Customer Reward Cycle - DATABASE FOUNDATION (hardening + missing pieces). Re-runnable.
-- Run AFTER 0038. Frontend does NOT need to change for this migration.
--
-- 0038 already created: mega_stores, mega_campaigns, mega_campaign_shops, mega_enrollments, mega_rewards and the
-- megastore_* / admin_megastore_* / join_mega_campaign / get_my_mega_rewards functions. Those tables are REUSED here.
-- Nothing is dropped. No existing RLS policy is weakened (one is extended to authorised members, see section 9).
--
-- NEW in this file
--   1. mega_store_members              authorised owners / managers of a Mega Store (primary owner is always a member)
--   2. mega_campaigns.budget_inr, .config   campaign budget + free configuration (json object)
--   3. mega_terms, mega_terms_acceptances   versioned campaign terms + who accepted what (customers and partner shops)
--   4. mega_partner_participation      partner shop invited / accepted / declined / withdrawn / removed
--   5. mega_service_verifications      the verified partner-shop service every reward must be linked to
--   6. mega_reward_redemptions         redemption records, kept SEPARATE from enrolments (participation)
--   7. mega_fraud_flags                fraud-review flags + decisions
--   8. mega_audit_log                  append-only audit trail (campaign, budget, reward, redemption, terms, flags ...)
--   9. Database-level guards (triggers) so the business rules hold even if a function is bypassed:
--        - one enrolment per customer per campaign (unique, from 0038) + customer must be a real active customer account
--        - max 5 rewards per customer per campaign (reward_seq 1..5 + partial unique index + count check, under a row lock)
--        - every reward is linked to customer + campaign + Mega Store + verified partner-shop service
--        - reward code is generated by the server (64-bit random, unpredictable); browser values for code / amount are ignored
--        - expires_at = issued_at + 1 month (UTC), forced by the server
--        - a reward can be redeemed once; redeemed / revoked / rejected are final; discount is re-checked against the formula
--        - campaign budget is enforced when a redemption is recorded
--        - campaign reward terms are locked after the draft stage
--
-- FINANCIAL RULE (unchanged): the Mega Store funds 100% of the discount; nothing here touches Blisscco credit / payment tables.
-- SECURITY: all new tables are read-only for API users (RLS select policies only). Every write goes through the security-definer
-- functions / triggers in this file. Nothing here needs, stores or exposes a service-role key.

