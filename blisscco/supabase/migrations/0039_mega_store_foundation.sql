-- ============ 4. HELPERS ============
-- Authorised owner = the primary owner (as before) OR an active member added by the primary owner. Suspended accounts never qualify.
create or replace function public.owns_mega_store(p_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.mega_stores m
                  where m.id = p_id
                    and exists (select 1 from public.profiles p where p.id = auth.uid() and not p.is_suspended)
                    and (m.owner_id = auth.uid()
                         or exists (select 1 from public.mega_store_members mm
                                     where mm.mega_store_id = m.id and mm.user_id = auth.uid() and mm.status = 'active')));
$$;

create or replace function public.owns_mega_campaign(p_campaign_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.mega_campaigns c where c.id = p_campaign_id and public.owns_mega_store(c.mega_store_id));
$$;

-- terms are readable when they are platform defaults, or the campaign is not a draft, or the reader runs it / is admin / is a selected partner
create or replace function public.mega_terms_visible(p_campaign_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select p_campaign_id is null or exists (
    select 1 from public.mega_campaigns c
     where c.id = p_campaign_id
       and (c.status <> 'draft' or public.owns_mega_store(c.mega_store_id) or public.is_admin()
            or exists (select 1 from public.mega_campaign_shops s where s.campaign_id = c.id and public.owns_business(s.business_id))));
$$;

-- current terms = newest version for the campaign, else newest platform default (internal)
create or replace function public.mega_current_terms(p_campaign_id uuid, p_scope text)
returns uuid language sql stable security definer set search_path = '' as $$
  select x.id from (
    select t.id, 1 as pri, t.version from public.mega_terms t where t.scope = p_scope and t.campaign_id = p_campaign_id
    union all
    select t.id, 2 as pri, t.version from public.mega_terms t where t.scope = p_scope and t.campaign_id is null
  ) x order by x.pri, x.version desc limit 1;
$$;

-- unpredictable reward identifier: 64 random bits from gen_random_uuid() (cryptographically strong), shown as text and QR
create or replace function public.mega_new_reward_code() returns text
language plpgsql volatile security definer set search_path = '' as $$
declare h text := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8) || substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
begin
  return 'MS-' || substr(h, 1, 4) || '-' || substr(h, 5, 4) || '-' || substr(h, 9, 4) || '-' || substr(h, 13, 4);
end $$;

-- internal audit writer (not callable by API users)
create or replace function public.mega_audit(p_action text, p_store uuid, p_campaign uuid, p_type text, p_id uuid, p_details jsonb)
returns void language plpgsql security definer set search_path = '' as $$
begin
  insert into public.mega_audit_log (actor_id, actor_role, mega_store_id, campaign_id, action, entity_type, entity_id, details)
  values (auth.uid(), (select p.role::text from public.profiles p where p.id = auth.uid()), p_store, p_campaign, p_action, p_type, p_id,
          coalesce(p_details, '{}'::jsonb));
end $$;

